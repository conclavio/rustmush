//! OOC adapter for the common detachment roster/order contract.
//!
//! This reuses the game's objective vocabulary without inheriting practice
//! squads, side grants or a fixed arena TTL. DT.1b's opt-in live host and cockpit
//! commands use the same contract. A dispatch is a message for a recipient
//! adapter; controller execution retains its own station, observations and
//! admission. In particular, a contact hint never becomes a known target.

pub mod commands;
pub mod live;
pub mod planning;

use mush_core::ObjId;
use mush_tactics::detachment::orders::{DeliveredOrder, Directive, OrderBook, OrderEnvelope};
use mush_tactics::detachment::roster::{Controller, DetachmentRoster, Slot};
use serde::Serialize;

use crate::arena::state::ContactId;
use crate::deliberation::order::{Constraints, Objective};

/// A bounded game objective. A hint stays opaque; its observation scope is
/// supplied by the admitted envelope, never cached from an earlier commander.
#[derive(Clone, Debug, PartialEq, Eq, Serialize)]
pub struct PracticeObjective {
    objective: Objective,
    constraints: Constraints,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, thiserror::Error)]
pub enum ObjectiveError {
    #[error("the destination lies outside the practice window")]
    OffWindow,
    #[error("the screen bearing must be below 360 degrees")]
    Facing,
    #[error("the support objective must name a roster member")]
    Support,
}

impl PracticeObjective {
    /// `window` is this OOC exercise's admitted (columns, rows), not an IC map
    /// policy. Contact ids remain opaque and are re-keyed by recipient hosts.
    pub fn new(
        roster: &DetachmentRoster,
        objective: Objective,
        constraints: Constraints,
        window: (u16, u16),
    ) -> Result<Self, ObjectiveError> {
        match objective {
            Objective::Advance { to } if to.0 >= window.0 || to.1 >= window.1 => {
                return Err(ObjectiveError::OffWindow);
            }
            Objective::Screen { facing_mdeg } if facing_mdeg >= 360_000 => {
                return Err(ObjectiveError::Facing);
            }
            Objective::Support { of } if !roster.members().iter().any(|row| row.unit == of) => {
                return Err(ObjectiveError::Support);
            }
            _ => {}
        }
        Ok(Self {
            objective,
            constraints,
        })
    }

    #[must_use]
    pub const fn objective(&self) -> Objective {
        self.objective
    }

    #[must_use]
    pub const fn constraints(&self) -> Constraints {
        self.constraints
    }
}

/// Derive the hint's scope from the admitted issuer's unit. Reusing an objective
/// after succession cannot read the former leader's contacts. A recipient must
/// still re-key the hint through its own actual observations before execution.
#[must_use]
pub fn scoped_target_hint(order: &OrderEnvelope<PracticeObjective>) -> Option<(ObjId, ContactId)> {
    match &order.directive {
        Directive::Objective(payload) => match payload.objective {
            Objective::Engage {
                target_hint: Some(contact),
            } => Some((order.issuer_unit, contact)),
            _ => None,
        },
        Directive::Cancel => None,
    }
}

/// The same order is presented to a player or offered to an execution adapter.
/// Neither variant is a physical control intent or proof of an attempt.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum RecipientDispatch<'a> {
    PlayerNotice {
        character: ObjId,
        order: &'a DeliveredOrder<PracticeObjective>,
    },
    ControllerMessage {
        /// Some is a real NPC character; None is an automated unit. No persona
        /// is generated by a player leaving or by constructing this projection.
        character: Option<ObjId>,
        order: &'a DeliveredOrder<PracticeObjective>,
    },
}

/// Project the current, delivered objective for its actual recipient. A new
/// pending order does not replace the old dispatch until communication delivers
/// it. Callers transport cancellations separately from active objectives.
#[must_use]
pub fn dispatch_for<'a>(
    roster: &DetachmentRoster,
    orders: &'a OrderBook<PracticeObjective>,
    slot: Slot,
    now_ms: u64,
) -> Option<RecipientDispatch<'a>> {
    orders.standing(roster, slot, now_ms)?;
    let order = orders.delivered(slot)?;
    Some(match order.order.recipient.controller {
        Controller::Player { character } => RecipientDispatch::PlayerNotice { character, order },
        Controller::Npc { character } => RecipientDispatch::ControllerMessage {
            character: Some(character),
            order,
        },
        Controller::Automated => RecipientDispatch::ControllerMessage {
            character: None,
            order,
        },
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use mush_tactics::detachment::orders::{
        Directive, ExecutionObservation, OrderRequest, OrderTarget, Response,
    };
    use mush_tactics::detachment::roster::{
        Connection, DetachmentId, LeadershipPolicy, Member, MemberFacts,
    };

    fn fixture() -> Result<DetachmentRoster, Box<dyn std::error::Error>> {
        let mut roster = DetachmentRoster::new(
            DetachmentId(1),
            1,
            vec![
                Member {
                    slot: Slot::new(1)?,
                    unit: ObjId(11),
                    controller: Controller::Automated,
                },
                Member {
                    slot: Slot::new(3)?,
                    unit: ObjId(13),
                    controller: Controller::Npc {
                        character: ObjId(103),
                    },
                },
                Member {
                    slot: Slot::new(4)?,
                    unit: ObjId(14),
                    controller: Controller::Player {
                        character: ObjId(104),
                    },
                },
                Member {
                    slot: Slot::new(6)?,
                    unit: ObjId(16),
                    controller: Controller::Player {
                        character: ObjId(106),
                    },
                },
            ],
            Some(ObjId(103)),
            LeadershipPolicy::default(),
        )?;
        let facts: Vec<_> = roster
            .members()
            .iter()
            .map(|member| MemberFacts {
                slot: member.slot,
                capable: true,
                controls_unit: true,
                unit_disabled: false,
                connection: Connection::Connected,
                command_authorized: true,
            })
            .collect();
        roster.reconcile(0, &facts)?;
        Ok(roster)
    }

    #[test]
    fn common_order_routes_to_player_npc_and_machine_without_execution()
    -> Result<(), Box<dyn std::error::Error>> {
        let roster = fixture()?;
        check_eq!(
            roster.leader().map(|leader| leader.character),
            Some(ObjId(104))
        );
        let mut orders = OrderBook::new(roster.id());
        let payload =
            PracticeObjective::new(&roster, Objective::Hold, Constraints::default(), (20, 20))?;
        let issued = orders.issue(
            &roster,
            0,
            OrderRequest {
                issuer: ObjId(104),
                roster_revision: roster.revision(),
                command_term: roster.term(),
                target: OrderTarget::All,
                directive: Directive::Objective(payload),
                expires_at_ms: None,
            },
            |_| true,
        )?;
        for slot in &issued.recipients {
            check!(dispatch_for(&roster, &orders, *slot, 0).is_none());
            orders.deliver(&roster, *slot, issued.sequence, 0, |_| true)?;
            let delivery = orders.delivered(*slot).ok_or("missing delivery")?;
            check!(delivery.acknowledgement.is_none());
            check!(delivery.attempted_at_ms.is_none());
            check!(delivery.completed_at_ms.is_none());
        }
        check!(matches!(
            dispatch_for(&roster, &orders, Slot::new(6)?, 0),
            Some(RecipientDispatch::PlayerNotice {
                character: ObjId(106),
                ..
            })
        ));
        check!(matches!(
            dispatch_for(&roster, &orders, Slot::new(3)?, 0),
            Some(RecipientDispatch::ControllerMessage {
                character: Some(ObjId(103)),
                ..
            })
        ));
        check!(matches!(
            dispatch_for(&roster, &orders, Slot::new(1)?, 0),
            Some(RecipientDispatch::ControllerMessage {
                character: None,
                ..
            })
        ));
        orders.respond(
            Slot::new(6)?,
            issued.sequence,
            ObjId(106),
            Response::Wilco,
            1,
        )?;
        check!(
            orders
                .delivered(Slot::new(6)?)
                .ok_or("missing player delivery")?
                .attempted_at_ms
                .is_none()
        );
        check!(
            orders
                .delivered(Slot::new(6)?)
                .ok_or("missing player delivery")?
                .completed_at_ms
                .is_none()
        );
        // An explicit authoritative report is distinct from WILCO. Recording
        // this observation changes history, without submitting a control intent.
        orders.observe_execution(
            Slot::new(6)?,
            issued.sequence,
            ExecutionObservation::Completed,
            2,
        )?;
        check!(dispatch_for(&roster, &orders, Slot::new(6)?, 2).is_none());
        // Standing DT orders do not expire at the simulator's ten-minute cap.
        check!(dispatch_for(&roster, &orders, Slot::new(1)?, 600_001).is_some());
        Ok(())
    }

    #[test]
    fn game_objectives_validate_without_simulator_ttl_or_side_policy()
    -> Result<(), Box<dyn std::error::Error>> {
        let mut roster = fixture()?;
        check_eq!(
            PracticeObjective::new(
                &roster,
                Objective::Advance { to: (20, 0) },
                Constraints::default(),
                (20, 20)
            ),
            Err(ObjectiveError::OffWindow)
        );
        check_eq!(
            PracticeObjective::new(
                &roster,
                Objective::Screen {
                    facing_mdeg: 360_000
                },
                Constraints::default(),
                (20, 20)
            ),
            Err(ObjectiveError::Facing)
        );
        check_eq!(
            PracticeObjective::new(
                &roster,
                Objective::Support { of: ObjId(999) },
                Constraints::default(),
                (20, 20)
            ),
            Err(ObjectiveError::Support)
        );
        let hint = ContactId(7);
        let objective = PracticeObjective::new(
            &roster,
            Objective::Engage {
                target_hint: Some(hint),
            },
            Constraints::default(),
            (20, 20),
        )?;
        let mut orders = OrderBook::new(roster.id());
        let issued = orders.issue(
            &roster,
            0,
            OrderRequest {
                issuer: ObjId(104),
                roster_revision: roster.revision(),
                command_term: roster.term(),
                target: OrderTarget::Slot(Slot::new(1)?),
                directive: Directive::Objective(objective.clone()),
                expires_at_ms: None,
            },
            |_| true,
        )?;
        check_eq!(
            scoped_target_hint(
                orders
                    .pending(Slot::new(1)?)
                    .ok_or("missing pending order")?
            ),
            Some((ObjId(14), hint))
        );
        let facts: Vec<_> = roster
            .members()
            .iter()
            .map(|member| MemberFacts {
                slot: member.slot,
                capable: member.unit != ObjId(14),
                controls_unit: true,
                unit_disabled: false,
                connection: Connection::Connected,
                command_authorized: true,
            })
            .collect();
        roster.reconcile(1, &facts)?;
        orders.issue(
            &roster,
            1,
            OrderRequest {
                issuer: ObjId(106),
                roster_revision: roster.revision(),
                command_term: roster.term(),
                target: OrderTarget::Slot(Slot::new(1)?),
                directive: Directive::Objective(objective),
                expires_at_ms: None,
            },
            |_| true,
        )?;
        let pending = orders
            .pending(Slot::new(1)?)
            .ok_or("missing successor order")?;
        check_ne!(pending.sequence, issued.sequence);
        check_eq!(scoped_target_hint(pending), Some((ObjId(16), hint)));
        Ok(())
    }
}
