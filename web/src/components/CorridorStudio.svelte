<script lang="ts">
  // Cut CS.4 — Corridor (`lane/ceres_phobos.json`) & Relays (`relays/luna_ceres.json`,
  // `relays/manufacture-v1.json`) Studio (doc 34 §5.2, D-34-6).
  import type { JsonValue } from "$lib/proto";
  import {
    type CorridorEntrySummary,
    type CorridorFilter,
    extractCorridorEntries,
    updateCorridorEntryDef,
  } from "$lib/content/corridor-editor";

  let {
    documentJson,
    onChange,
  }: {
    documentJson: JsonValue | null;
    onChange: (nextDoc: JsonValue) => void;
  } = $props();

  let filter = $state<CorridorFilter>("all");
  let selectedId = $state<string | null>(null);

  const entries = $derived<CorridorEntrySummary[]>(
    extractCorridorEntries(documentJson),
  );

  const filteredEntries = $derived<CorridorEntrySummary[]>(
    entries.filter((e) => {
      if (filter === "all") return true;
      return e.kind === filter;
    }),
  );

  $effect(() => {
    const first = filteredEntries[0];
    if (
      first &&
      (!selectedId || !filteredEntries.some((e) => e.id === selectedId))
    ) {
      selectedId = first.id;
    } else if (filteredEntries.length === 0) {
      selectedId = null;
    }
  });

  const activeEntry = $derived<CorridorEntrySummary | null>(
    entries.find((e) => e.id === selectedId) ?? null,
  );

  function patchField(key: string, value: unknown): void {
    if (!documentJson || !activeEntry || activeEntry.readOnly) return;
    const nextDef: Record<string, unknown> = {
      ...activeEntry.def,
      [key]: value,
    };
    onChange(updateCorridorEntryDef(documentJson, activeEntry.id, nextDef));
  }

  function patchSubJson(key: string, rawText: string): void {
    if (!documentJson || !activeEntry || activeEntry.readOnly) return;
    try {
      const parsed = JSON.parse(rawText);
      patchField(key, parsed);
    } catch {
      // Wait for valid JSON before patching
    }
  }
</script>

<div class="corridor-studio">
  <div class="corridor-filter-bar">
    {#each [
      ["all", "All"],
      ["port", "Ports (11)"],
      ["route", "Routes (20)"],
      ["location", "Locations (12)"],
      ["body", "Ephemeris Bodies (16, read-only)"],
      ["relay", "Relays & Manufacture"],
    ] as [id, label] (id)}
      <button
        type="button"
        class="filter-pill"
        class:active={filter === id}
        onclick={() => (filter = id as CorridorFilter)}
      >
        {label}
      </button>
    {/each}
  </div>

  <div class="corridor-columns">
    <div class="entry-list">
      {#each filteredEntries as entry (entry.id)}
        <button
          type="button"
          class="entry-card"
          class:active={entry.id === selectedId}
          onclick={() => (selectedId = entry.id)}
        >
          <div class="row-top">
            <strong>{entry.label}</strong>
            <span class="kind-chip">{entry.kind}</span>
          </div>
          <div class="row-sub">
            <code>{entry.id}</code> · {entry.subtitle}
          </div>
        </button>
      {/each}
    </div>

    {#if activeEntry}
      <div class="entry-inspector">
        <div class="inspector-head">
          <h4>
            {activeEntry.label} (<code>{activeEntry.id}</code>)
          </h4>
          {#if activeEntry.readOnly}
            <span class="ro-badge">Read-Only (JPL Horizons ephemeris)</span>
          {/if}
        </div>

        {#if activeEntry.kind === "body"}
          <div class="ro-notice">
            Generated by <code>fetch_horizons.py</code>. Orbital element tables are read-only in the browser to preserve astrological precision.
          </div>
          <pre class="ro-pre">{JSON.stringify(activeEntry.def, null, 2)}</pre>
        {:else if activeEntry.kind === "port"}
          <div class="field-grid">
            <label>
              <span>Venue Name</span>
              <input
                type="text"
                value={String(activeEntry.def.venue ?? "")}
                oninput={(e) => patchField("venue", (e.currentTarget as HTMLInputElement).value)}
              />
            </label>
            <label>
              <span>Location Ref</span>
              <input
                type="text"
                value={String(activeEntry.def.location ?? "")}
                oninput={(e) => patchField("location", (e.currentTarget as HTMLInputElement).value)}
              />
            </label>
            <label>
              <span>Neighborhood Area Ref</span>
              <input
                type="text"
                value={String(activeEntry.def.area ?? "")}
                oninput={(e) => patchField("area", (e.currentTarget as HTMLInputElement).value)}
              />
            </label>
          </div>

          <label class="sub-editor">
            <span>Port Room Role Bindings (<code>rooms</code>)</span>
            <textarea
              rows="5"
              value={JSON.stringify(activeEntry.def.rooms ?? {}, null, 2)}
              onchange={(e) => patchSubJson("rooms", (e.currentTarget as HTMLTextAreaElement).value)}
            ></textarea>
          </label>

          <label class="sub-editor">
            <span>Nested Orgs (<code>orgs</code> — desks &amp; relationships)</span>
            <textarea
              rows="5"
              value={JSON.stringify(activeEntry.def.orgs ?? [], null, 2)}
              onchange={(e) => patchSubJson("orgs", (e.currentTarget as HTMLTextAreaElement).value)}
            ></textarea>
          </label>

          <label class="sub-editor">
            <span>Nested Vendors (<code>vendors</code> — signatory, counter, stock, asks, bids, mill, programme, vehicles)</span>
            <textarea
              rows="8"
              value={JSON.stringify(activeEntry.def.vendors ?? [], null, 2)}
              onchange={(e) => patchSubJson("vendors", (e.currentTarget as HTMLTextAreaElement).value)}
            ></textarea>
          </label>

          {#if activeEntry.def.site}
            <label class="sub-editor">
              <span>Mining Site &amp; Claim Blocks (<code>site</code> — blocks A–P &amp; yard)</span>
              <textarea
                rows="6"
                value={JSON.stringify(activeEntry.def.site, null, 2)}
                onchange={(e) => patchSubJson("site", (e.currentTarget as HTMLTextAreaElement).value)}
              ></textarea>
            </label>
          {/if}
        {:else if activeEntry.kind === "route"}
          <div class="field-grid">
            <label>
              <span>Origin Location</span>
              <input
                type="text"
                value={String(activeEntry.def.origin ?? "")}
                oninput={(e) => patchField("origin", (e.currentTarget as HTMLInputElement).value)}
              />
            </label>
            <label>
              <span>Destination Location</span>
              <input
                type="text"
                value={String(activeEntry.def.destination ?? "")}
                oninput={(e) => patchField("destination", (e.currentTarget as HTMLInputElement).value)}
              />
            </label>
            <label>
              <span>Duration (seconds)</span>
              <input
                type="number"
                value={Number(activeEntry.def.duration_seconds ?? 0)}
                oninput={(e) =>
                  patchField("duration_seconds", Number((e.currentTarget as HTMLInputElement).value))}
              />
            </label>
          </div>
          <label class="sub-editor">
            <span>Distance &amp; Waypoints (<code>distance</code>, <code>waypoints</code>)</span>
            <textarea
              rows="6"
              value={JSON.stringify(
                {
                  distance: activeEntry.def.distance,
                  waypoints: activeEntry.def.waypoints,
                },
                null,
                2,
              )}
              onchange={(e) => {
                try {
                  const parsed = JSON.parse((e.currentTarget as HTMLTextAreaElement).value);
                  if (parsed.distance !== undefined) patchField("distance", parsed.distance);
                  if (parsed.waypoints !== undefined) patchField("waypoints", parsed.waypoints);
                } catch {
                  // Ignore invalid intermediate JSON
                }
              }}
            ></textarea>
          </label>
        {:else if activeEntry.kind === "location"}
          <div class="field-grid">
            <label>
              <span>Role (<code>station | body | anchor</code>)</span>
              <input
                type="text"
                value={String(activeEntry.def.role ?? "")}
                oninput={(e) => patchField("role", (e.currentTarget as HTMLInputElement).value)}
              />
            </label>
            <label>
              <span>Region</span>
              <input
                type="text"
                value={String(activeEntry.def.region ?? "")}
                oninput={(e) => patchField("region", (e.currentTarget as HTMLInputElement).value)}
              />
            </label>
          </div>
          <label class="sub-editor">
            <span>Anchor &amp; Coordinates (<code>anchor</code>)</span>
            <textarea
              rows="6"
              value={JSON.stringify(activeEntry.def.anchor ?? {}, null, 2)}
              onchange={(e) => patchSubJson("anchor", (e.currentTarget as HTMLTextAreaElement).value)}
            ></textarea>
          </label>
        {:else}
          <!-- Relays (`network` nodes & pairs, `private_pair` manufacture recipe, or `sol` region) -->
          {#if activeEntry.def.nodes || activeEntry.def.pairs}
            <label class="sub-editor">
              <span>Relay Nodes (<code>nodes</code> — port, room, capacity, operator)</span>
              <textarea
                rows="7"
                value={JSON.stringify(activeEntry.def.nodes ?? {}, null, 2)}
                onchange={(e) => patchSubJson("nodes", (e.currentTarget as HTMLTextAreaElement).value)}
              ></textarea>
            </label>
            <label class="sub-editor">
              <span>Entangled Pairs (<code>pairs</code> — endpoints, bandwidth, tariff)</span>
              <textarea
                rows="7"
                value={JSON.stringify(activeEntry.def.pairs ?? {}, null, 2)}
                onchange={(e) => patchSubJson("pairs", (e.currentTarget as HTMLTextAreaElement).value)}
              ></textarea>
            </label>
          {:else}
            <label class="sub-editor">
              <span>Entry Definition (<code>{activeEntry.id}</code>)</span>
              <textarea
                rows="10"
                value={JSON.stringify(activeEntry.def, null, 2)}
                onchange={(e) => {
                  if (!documentJson) return;
                  try {
                    const parsed = JSON.parse((e.currentTarget as HTMLTextAreaElement).value);
                    onChange(updateCorridorEntryDef(documentJson, activeEntry.id, parsed));
                  } catch {
                    // Wait for valid JSON
                  }
                }}
              ></textarea>
            </label>
          {/if}
        {/if}
      </div>
    {/if}
  </div>
</div>

